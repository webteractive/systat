import Foundation

/// The sh helper that swaps a new systat.app into place after the running one quits.
/// A running app can't replace itself, so the app stages the new bundle, starts this helper, and quits.
///
/// The installed app is never deleted before its replacement is verified (zetty's 0.1.40 crash was
/// a helper that ran `rm -rf` then a copy, and a cut-short copy left a bundle that couldn't launch):
/// - it waits for the app's PID *with the app's start time*, so a reused PID doesn't hold it up,
///   and an app that never quits means nothing changes,
/// - one swap at a time, under a `lockf` lock the kernel drops if its holder dies,
/// - the staged bundle must be a real folder (not a symlink) that passes `codesign --verify`
///   before the installed one is touched,
/// - the installed bundle is moved aside, not deleted, and the new one is moved in whole: both are
///   renames, since the app stages on the target's own volume,
/// - if the move or the verify after it fails, the old bundle is put back.
/// It writes one line to the result file ("installed X" or "failed: why") for the app to read on its
/// next launch, and ends by relaunching the installed app if it verifies, so a failed update leaves a
/// working app and a foreign one in the slot is never opened.
public enum SwapScript {
    /// `requirement` is a code-signing requirement both bundles must meet; nil checks the signature
    /// only. `relaunch` is the command that opens the installed app.
    public static func render(appPID: Int32, appStart: String, target: String, staged: String, workDir: String,
                              lockFile: String, resultFile: String, requirement: String?,
                              relaunch: String = "/usr/bin/open",
                              quitTimeoutTenths: Int = 300, lockTimeout: Int = 120) -> String {
        let requirementFlag = requirement.map { " -R=" + quote($0) } ?? ""
        return """
        #!/bin/sh
        # systat update helper, generated by SwapScript. Safe to delete.
        # The system's own tools only, and no hang-up or interrupt halfway through a swap when the
        # terminal that ran systat --update closes.
        PATH=/usr/bin:/bin:/usr/sbin:/sbin; export PATH
        trap '' HUP INT TERM
        TARGET=\(quote(target))
        STAGED=\(quote(staged))
        WORKDIR=\(quote(workDir))
        LOCK=\(quote(lockFile))
        RESULT=\(quote(resultFile))
        BACKUP="$WORKDIR/previous.app"

        verify() {
            [ -d "$1" ] && [ ! -L "$1" ] && /usr/bin/codesign --verify --deep --strict\(requirementFlag) "$1" >/dev/null 2>&1
        }
        version() {
            /usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$1/Contents/Info.plist" 2>/dev/null
        }

        if [ "$1" = swap ]; then
            # Holding the lock: no other systat update is swapping.
            if ! verify "$STAGED"; then
                echo "failed: the new version didn't verify" > "$RESULT"; exit 0
            fi
            if [ -L "$TARGET" ] || ! /bin/mv "$TARGET" "$BACKUP"; then
                echo "failed: the installed app couldn't be moved aside" > "$RESULT"; exit 0
            fi
            if /bin/mv "$STAGED" "$TARGET" && verify "$TARGET"; then
                echo "installed $(version "$TARGET")" > "$RESULT"
            else
                # Restore only into an empty slot: mv onto an existing folder would nest inside it.
                [ -e "$TARGET" ] && /bin/mv "$TARGET" "$WORKDIR/failed.app"
                if [ ! -e "$TARGET" ] && /bin/mv "$BACKUP" "$TARGET"; then
                    echo "failed: the new version didn't install, so the old one was put back" > "$RESULT"
                else
                    echo "failed: the update couldn't finish; the previous app is at $BACKUP" > "$RESULT"
                fi
            fi
            exit 0
        fi

        # Wait for the app to quit: this PID with this start time, so a reused PID doesn't count.
        # ps prints nothing for a PID that's gone, so an empty start time never counts as running.
        APPSTART=\(quote(appStart))
        i=0
        while [ -n "$APPSTART" ] && [ "$(/bin/ps -o lstart= -p \(appPID) 2>/dev/null)" = "$APPSTART" ]; do
            i=$((i + 1))
            if [ "$i" -ge \(quitTimeoutTenths) ]; then
                # It never quit, so it's still running: change nothing and open nothing.
                /bin/rm -rf "$WORKDIR"; exit 1
            fi
            /bin/sleep 0.1
        done

        /bin/rm -f "$RESULT"
        if ! /usr/bin/lockf -k -s -t \(lockTimeout) "$LOCK" /bin/sh "$0" swap; then
            echo "failed: another update was in progress" > "$RESULT"
        fi
        # Open only an app that verifies: whatever else is in the slot is never launched as this
        # user. And never delete the work folder while it may hold the only copy of the app.
        if verify "$TARGET"; then
            /bin/rm -rf "$WORKDIR"
            \(relaunch) "$TARGET"
        elif [ ! -e "$BACKUP" ]; then
            /bin/rm -rf "$WORKDIR"
        fi
        """
    }

    /// The start time `ps` reports for `pid`, exactly as the script compares it; nil if it isn't running.
    public static func startTime(of pid: Int32) -> String? {
        let ps = Process()
        let pipe = Pipe()
        ps.executableURL = URL(fileURLWithPath: "/bin/ps")
        ps.arguments = ["-o", "lstart=", "-p", "\(pid)"]
        ps.standardOutput = pipe
        ps.standardError = FileHandle.nullDevice
        guard (try? ps.run()) != nil else { return nil }
        let data = pipe.fileHandleForReading.readDataToEndOfFile()
        ps.waitUntilExit()
        // As sh's $(...) does: drop trailing newlines only.
        var text = String(decoding: data, as: UTF8.self)
        while text.hasSuffix("\n") { text.removeLast() }
        return ps.terminationStatus == 0 && !text.isEmpty ? text : nil
    }

    /// Single-quotes a value for sh.
    public static func quote(_ value: String) -> String {
        "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }
}
